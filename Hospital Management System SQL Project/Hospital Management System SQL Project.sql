SELECT DOCTOR_NAME, SUM(consultation_fee) AS TOTAL_REVENUE
FROM DOCTORS
INNER JOIN APPOINTMENTS
ON DOCTORS.DOCTOR_ID = APPOINTMENTS.DOCTOR_ID
GROUP BY DOCTOR_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 1;

SELECT PATIENT_NAME, COUNT(APPOINTMENT_DATE) AS TOTAL_VISIT
FROM PATIENTS
INNER JOIN APPOINTMENTS
ON PATIENTS.PATIENT_ID = APPOINTMENTS.PATIENT_ID
GROUP BY PATIENT_NAME
ORDER BY TOTAL_VISIT DESC
LIMIT 1;

