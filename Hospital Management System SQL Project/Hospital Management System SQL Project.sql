SELECT SUM(consultation_fee) AS TOTAL_CONSULTATION_FEE
FROM APPOINTMENTS;

SELECT AVG(consultation_fee) AS AVG_CONSULTATION_FEE
FROM APPOINTMENTS;

SELECT MAX(CONSULTATION_FEE) AS MAX_CONSULTAION_FEE
FROM APPOINTMENTS;

SELECT MIN(CONSULTATION_FEE) AS MIN_CONSULTAION_FEE
FROM APPOINTMENTS;

SELECT COUNT(APPOINTMENT_ID) AS TOTAL_APPOINTMENTS
FROM APPOINTMENTS;

SELECT DOCTOR_NAME, COUNT(APPOINTMENT_ID) AS APPOINMENTS_OF_DOCTORS
FROM DOCTORS
INNER JOIN APPOINTMENTS
ON DOCTORS.DOCTOR_ID = APPOINTMENTS.DOCTOR_ID
GROUP BY DOCTOR_NAME;

SELECT DOCTOR_NAME, SUM(consultation_fee) AS TOTAL_CONSULTATION_FEES
FROM DOCTORS
