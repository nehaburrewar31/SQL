SELECT MONTH(APPOINTMENT_DATE) AS MONTH, 
       COUNT(APPOINTMENT_ID) AS APPOINTMENT_COUNT
  FROM APPOINTMENTS
  GROUP BY MONTH(APPOINTMENT_DATE)
  ORDER BY MONTH;

