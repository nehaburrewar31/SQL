FROM ORDERS;

SELECT COUNT(ORDER_ID) AS NO_OF_ORDERS
FROM ORDERS;

SELECT CITY, COUNT(ORDER_ID)
FROM CUSTOMERS
INNER JOIN ORDERS
ON CUSTOMERS.CUSTOMER_ID = ORDERS.CUSTOMER_ID
GROUP BY CITY;

SELECT RESTAURANT_NAME, SUM(ORDER_AMOUNT) AS TOTAL_REVENUE
FROM RESTAURANTS
INNER JOIN ORDERS
ON RESTAURANTS.RESTAURANT_ID = ORDERS.RESTAURANT_ID
GROUP BY RESTAURANT_NAME;

